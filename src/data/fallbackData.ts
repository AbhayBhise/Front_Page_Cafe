export function getFallbackCafes(params: { q?: string; city?: string; page?: number; pageSize?: number } = {}): Paginated<Cafe> {
  let list = [...FALLBACK_CAFES];
  if (params.q) {
    const q = params.q.toLowerCase();
    list = list.filter((c) => c.name.toLowerCase().includes(q) || (c.city && c.city.toLowerCase().includes(q)));
  }
  if (params.city) {
    const city = params.city.toLowerCase();
    list = list.filter((c) => c.city && c.city.toLowerCase() === city);
  }
  const page = params.page || 1;
  const pageSize = params.pageSize || 30;
  return {
    data: list.slice((page - 1) * pageSize, page * pageSize),
    meta: {
      page,
      pageSize,
      total: list.length,
      pages: Math.ceil(list.length / pageSize),
    },
  };
}

export function getFallbackMenu(idOrSlug: string): PublicMenu {
  const menu = FALLBACK_PUBLIC_MENUS[idOrSlug] || FALLBACK_PUBLIC_MENUS['front-page-cafe'];
  return menu;
}
